#!/usr/bin/env python3
"""Inventory and validate Atlas translations using OpenYAMM's existing PO tools."""

import argparse
import collections
import json
from pathlib import Path
import re

import l10n

ROOT = Path(__file__).resolve().parents[1]
SOURCE_PREFIXES = ('game/world/World', 'game/ui/screens/Atlas', 'game/items/ItemInspectionText',
                   'game/events/EventAttributeInfo.h')


def inventory():
    class AtlasTemplate(l10n.Template):
        def add(self, domain, msgid, reference, **kwargs):
            if reference.startswith(SOURCE_PREFIXES):
                super().add('engine', msgid, reference, **kwargs)

    template = AtlasTemplate()
    l10n.extract_cpp(template)
    # Generated sidecars remain English and are regenerated by the exporter. Translate their complete reading
    # paragraphs in PO files, preserving the event scripts and their ownership.
    for path in sorted((ROOT / 'assets_dev').rglob('*_00_site_refs.lua')):
        text = path.read_text(encoding='utf-8')
        for match in re.finditer(r'Set(?:Map|Global)SiteReference\(\d+,\s*("(?:[^"\\]|\\.)*")\)', text):
            paragraph = json.loads(match[1])
            line = text.count('\n', 0, match.start()) + 1
            l10n.Template.add(template, 'engine', paragraph,
                             f'{path.relative_to(ROOT)}:{line}')
    # Skill display labels come from the shared registry, not its canonical lookup keys.
    skills = ROOT / 'game/party/SkillData.cpp'
    skill_text = skills.read_text(encoding='utf-8')
    start = skill_text.index('DisplaySkillNames =')
    end = skill_text.index('};', start)
    for match in re.finditer(r'Engine::trNoop\(\s*("(?:[^"\\]|\\.)*")', skill_text[start:end]):
        l10n.Template.add(template, 'engine', json.loads(match[1]),
                         f'game/party/SkillData.cpp:{skill_text.count(chr(10), 0, start + match.start()) + 1}')
    # The Atlas presents the equipment category, which the ordinary game keeps as a table identifier.
    # Collect that displayed column explicitly rather than translating or rewriting the gameplay table.
    items = ROOT / 'assets_dev/engine/data_tables/items.txt'
    for line, row in l10n.parse_table(l10n.read_text(items))[2:]:
        if len(row) > 4 and row[4] and row[4] != '0':
            key = ('atlas.itemtype', row[4])
            entry = template.domains['engine'].setdefault(key, l10n.Entry(row[4], key[0]))
            entry.references.append(f'assets_dev/engine/data_tables/items.txt:{line}')
    entries = template.domains['engine']
    return sorted(entries.values(), key=lambda entry: entry.key)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--template', type=Path, help='Write the current Atlas POT')
    parser.add_argument('--catalog', type=Path, help='Check an Atlas PO file')
    parser.add_argument('--json', type=Path, help='Write a machine-readable inventory')
    args = parser.parse_args()
    entries = inventory()
    if args.template:
        l10n.write_po(args.template, l10n.template_header(), entries)
    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(json.dumps([{'text': e.msgid, 'plural': e.plural, 'context': e.context,
                                         'references': e.references} for e in entries],
                                       ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'Atlas: {len(entries)} translation entries, {sum(len(e.msgid.split()) for e in entries)} source words')
    if args.catalog:
        _, translated = l10n.parse_po(args.catalog.read_text(encoding='utf-8'))
        catalog = {e.key: e for e in translated if not e.obsolete}
        missing, invalid = [], []
        for entry in entries:
            target = catalog.get(entry.key)
            if target is None or not target.translated():
                missing.append(entry.msgid)
                continue
            for text in target.msgstr:
                if collections.Counter(re.findall(r'\{[^{}]+\}', entry.msgid)) != collections.Counter(
                        re.findall(r'\{[^{}]+\}', text)):
                    invalid.append(entry.msgid)
        print(f'Catalog: {len(missing)} missing, {len(invalid)} placeholder mismatches')
        if missing or invalid:
            raise SystemExit(1)


if __name__ == '__main__':
    main()
